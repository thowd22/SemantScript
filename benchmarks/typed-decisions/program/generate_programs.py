"""Write the four typed-decisions workflows as SemantScript programs.

Every workflow of the LocalLLaMA/typed-decisions suite asks five typed
questions about one JSON state. This script reads the question schema of each
workflow from the pinned dataset (it is identical for every case of a workflow)
and writes ``<workflow>.sem.ts`` with one ``sema`` expression per question over
the case's ``state`` JSON string: a ``choice`` question becomes a string-literal
union of its option names, a ``noul`` question a ``boolean``, and a ``score``
question a ``BoundedInt`` over its rubric levels. The instructions and every
option or level description go into the behavioral text, since the card says
they are part of the input. The first line of each text names the question so
the training driver can pair functions with dataset columns.

Usage::

    PYTHONNOUSERSITE=1 PYTHONPATH=.python-packages python3 \\
        benchmarks/typed-decisions/program/generate_programs.py
"""

from __future__ import annotations

import argparse
import glob
import json
import re
from pathlib import Path

DATASET = "LocalLLaMA/typed-decisions"
DATASET_REVISION = "c76749ec58bd8c3d2ea706b31c333a9059c38f90"
WORKFLOWS = (
    "agent_trace_observability",
    "customer_service",
    "invoice_processing",
    "security_incidents",
)
_IDENTIFIER = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


def dataset_root() -> Path:
    candidates = glob.glob(
        str(
            Path.home()
            / ".cache/huggingface/hub/datasets--LocalLLaMA--typed-decisions/snapshots"
            / DATASET_REVISION
        )
    )
    if not candidates:
        raise SystemExit(f"download {DATASET} at {DATASET_REVISION} first")
    return Path(candidates[0])


def question_schema(root: Path, workflow: str) -> dict[str, dict]:
    import pyarrow.parquet as pq

    rows = pq.read_table(str(root / workflow / "train-00000-of-00001.parquet")).to_pylist()
    schemas = {row["questions"] for row in rows}
    if len(schemas) != 1:
        raise SystemExit(f"{workflow}: question schema differs between cases")
    return json.loads(schemas.pop())


def ts_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def template_text(value: str) -> str:
    return value.replace("\\", "\\\\").replace("`", "\\`").replace("${", "\\${")


def criteria_of(spec: dict) -> dict | list:
    """A noul question may omit its criteria; the answer is still true or false."""

    criteria = spec.get("criteria")
    if criteria is None and spec["type"] == "noul":
        return {"false": "The statement does not hold.", "true": "The statement holds."}
    if criteria is None:
        raise SystemExit(f"question of type {spec['type']} has no criteria")
    return criteria


def output_type(name: str, spec: dict) -> str:
    kind = spec["type"]
    criteria = criteria_of(spec)
    if kind == "choice":
        return " | ".join(ts_string(option) for option in criteria)
    if kind == "noul":
        return "boolean"
    if kind == "score":
        return f"BoundedInt<0, {len(criteria) - 1}>"
    raise SystemExit(f"{name}: unsupported question type {kind}")


def behavioral_text(name: str, spec: dict) -> list[str]:
    lines = [f"Question: {name}", spec["instructions"].strip()]
    criteria = criteria_of(spec)
    if spec["type"] == "score":
        lines.append("Answer with the level whose description fits best:")
        lines.extend(f"{index}: {text}" for index, text in enumerate(criteria))
    elif spec["type"] == "choice":
        lines.append("Options:")
        lines.extend(f"{option}: {text}" for option, text in criteria.items())
    else:
        lines.append("Answer true or false:")
        lines.extend(f"{option}: {text}" for option, text in criteria.items())
    lines.append("State (JSON): ${state}")
    return lines


def render(workflow: str, schema: dict[str, dict]) -> str:
    needs_bounded = any(spec["type"] == "score" for spec in schema.values())
    imports = (
        'import { sema, type BoundedInt } from "@semantscript/core";'
        if needs_bounded
        else 'import { sema } from "@semantscript/core";'
    )
    parts = [
        f"// Generated by generate_programs.py from {DATASET}@{DATASET_REVISION[:8]},",
        f"// workflow {workflow}: one sema expression per question over the case state.",
        imports,
        "",
        f"export interface {pascal(workflow)}Decisions {{",
    ]
    for name, spec in schema.items():
        parts.append(f"  {name}: {output_type(name, spec)};")
    parts.append("}")
    parts.append("")
    parts.append(
        f"export function {camel(workflow)}(state: string): {pascal(workflow)}Decisions {{"
    )
    for name, spec in schema.items():
        if not _IDENTIFIER.match(name):
            raise SystemExit(f"{workflow}: question {name!r} is not an identifier")
        body = "\n".join(f"    {template_text(line)}" for line in behavioral_text(name, spec))
        parts.append(f"  const {name} = sema<{output_type(name, spec)}>`")
        parts.append(body)
        parts.append("  `;")
    parts.append("  return { " + ", ".join(schema) + " };")
    parts.append("}")
    return "\n".join(parts) + "\n"


def pascal(name: str) -> str:
    return "".join(part.capitalize() for part in name.split("_"))


def camel(name: str) -> str:
    head, *rest = name.split("_")
    return head + "".join(part.capitalize() for part in rest)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n", 1)[0])
    parser.add_argument("--output", type=Path, default=Path(__file__).resolve().parent)
    arguments = parser.parse_args(argv)
    root = dataset_root()
    for workflow in WORKFLOWS:
        schema = question_schema(root, workflow)
        (arguments.output / f"{workflow}.sem.ts").write_text(
            render(workflow, schema), encoding="utf-8"
        )
        print(f"wrote {workflow}.sem.ts with {len(schema)} questions")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
