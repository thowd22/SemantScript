// Generates every printed remedy from diagnostics/remedies.json, the one source
// for the fix the tools print and the fix column of docs/diagnostics.md:
//
//   runtime/src/remedies.generated.ts                    (runtime)
//   compiler/src/remedies.generated.ts                   (editor plugin and CLI)
//   trainer/src/semantscript_trainer/remedies_generated.py (trainer and its doctor)
//   docs/diagnostics.md, between <!-- remedies:<family>:begin/end --> markers
//
// `node scripts/generate-remedies.mjs` rewrites them; `--check` writes nothing
// and exits 1 naming each stale file (runtime/test/remedies.test.mjs runs it).
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = join(root, "diagnostics", "remedies.json");
const TS_OUTPUTS = [
  join(root, "runtime", "src", "remedies.generated.ts"),
  join(root, "compiler", "src", "remedies.generated.ts"),
];
const PY_OUTPUT = join(
  root,
  "trainer",
  "src",
  "semantscript_trainer",
  "remedies_generated.py",
);
const DOCS = join(root, "docs", "diagnostics.md");
const ID = /^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/u;
const PLACEHOLDER = /\{([a-z][a-zA-Z0-9]*)\}/gu;
const HEADER =
  "Generated by scripts/generate-remedies.mjs from diagnostics/remedies.json; do not edit.";

/** Parse and validate the source; returns the families and the remedies in order. */
export function loadRemedies(path = SOURCE) {
  const document = JSON.parse(readFileSync(path, "utf8"));
  if (document.kind !== "semantscript.remedies" || document.version !== 1) {
    throw new Error(
      `${path} must be a semantscript.remedies version 1 document`,
    );
  }
  const families = document.families;
  if (families === null || typeof families !== "object") {
    throw new Error(`${path}: families must be an object`);
  }
  const seen = new Set();
  const remedies = document.remedies.map((entry, index) => {
    const where = `${path}: remedies[${String(index)}]`;
    for (const key of ["id", "family", "failure", "cause", "fix"]) {
      if (typeof entry[key] !== "string" || entry[key].length === 0) {
        throw new Error(`${where}.${key} must be a non-empty string`);
      }
    }
    const extra = Object.keys(entry).filter(
      (key) => !["id", "family", "failure", "cause", "fix"].includes(key),
    );
    if (extra.length > 0) {
      throw new Error(`${where} has unknown keys ${extra.join(", ")}`);
    }
    if (!ID.test(entry.id) || seen.has(entry.id)) {
      throw new Error(`${where}.id ${entry.id} is not a unique kebab-case id`);
    }
    seen.add(entry.id);
    if (!Object.hasOwn(families, entry.family)) {
      throw new Error(`${where}.family ${entry.family} is not a family`);
    }
    for (const text of [entry.failure, entry.cause, entry.fix]) {
      if (text.includes("|") || text.includes("\n")) {
        throw new Error(`${where} must not contain | or a line break`);
      }
    }
    if (entry.fix.includes("`")) {
      throw new Error(`${where}.fix must not contain a backtick`);
    }
    const params = [
      ...new Set([...entry.fix.matchAll(PLACEHOLDER)].map((match) => match[1])),
    ];
    return { ...entry, params };
  });
  return { families, remedies };
}

/** A string literal as Prettier prints it: double quotes unless single quotes need fewer escapes. */
function tsString(value) {
  const doubled = JSON.stringify(value);
  if (!value.includes('"') || value.includes("'")) return doubled;
  return `'${doubled.slice(1, -1).replaceAll('\\"', '"')}'`;
}

/** The generated TypeScript table, already in Prettier's layout. */
function typescriptModule(remedies) {
  const lines = [`// ${HEADER}`, "export const REMEDY_TEMPLATES = {"];
  for (const entry of remedies) {
    const params = `    params: [${entry.params.map(tsString).join(", ")}],`;
    lines.push(
      `  ${tsString(entry.id)}: {`,
      `    family: ${tsString(entry.family)},`,
      `    fix: ${tsString(entry.fix)},`,
      ...(params.length <= 80
        ? [params]
        : [
            "    params: [",
            ...entry.params.map((name) => `      ${tsString(name)},`),
            "    ],",
          ]),
      "  },",
    );
  }
  lines.push("} as const;", "", FORMATTER);
  return lines.join("\n");
}

/** The formatter both TypeScript packages carry, already in Prettier's layout. */
const FORMATTER = `/** Every remedy a tool prints, keyed by its id in \`diagnostics/remedies.json\`. */
export type RemedyId = keyof typeof REMEDY_TEMPLATES;

/** The placeholders one remedy's fix template names. */
export type RemedyParams<Id extends RemedyId> = Readonly<
  Record<(typeof REMEDY_TEMPLATES)[Id]["params"][number], string | number>
>;

/** The family a remedy belongs to (verifier, trainer-process, runtime, cli, doctor or editor). */
export function remedyFamily(id: RemedyId): string {
  return template(id).family;
}

/**
 * The fix text a tool prints for a failure: the template from
 * \`diagnostics/remedies.json\` with every \`{name}\` replaced by \`params[name]\`.
 * An unknown id, a missing parameter or one the template does not name is a
 * programming error and throws.
 */
export function remedy<Id extends RemedyId>(
  id: Id,
  ...args: (typeof REMEDY_TEMPLATES)[Id]["params"] extends readonly []
    ? []
    : [params: RemedyParams<Id>]
): string {
  const entry = template(id);
  const params: Readonly<Record<string, string | number>> = args[0] ?? {};
  const names: readonly string[] = entry.params;
  for (const key of Object.keys(params)) {
    if (!names.includes(key)) {
      throw new TypeError(\`remedy \${id} has no parameter \${key}\`);
    }
  }
  return entry.fix.replace(/\\{([a-z][a-zA-Z0-9]*)\\}/gu, (_match, name) => {
    const value = params[name as string];
    if (value === undefined) {
      throw new TypeError(\`remedy \${id} needs parameter \${String(name)}\`);
    }
    return String(value);
  });
}

function template(id: string): {
  readonly family: string;
  readonly fix: string;
  readonly params: readonly string[];
} {
  if (!Object.hasOwn(REMEDY_TEMPLATES, id)) {
    throw new TypeError(\`unknown remedy \${JSON.stringify(id)}\`);
  }
  return REMEDY_TEMPLATES[id as RemedyId];
}
`;

function pythonModule(remedies) {
  const table = Object.fromEntries(
    remedies.map((entry) => [
      entry.id,
      { family: entry.family, fix: entry.fix, params: entry.params },
    ]),
  );
  const text = JSON.stringify(table, null, 1);
  if (text.includes('"""') || text.endsWith("\\")) {
    throw new Error("a remedy cannot be embedded in a raw Python string");
  }
  return `"""${HEADER}"""

REMEDY_TEMPLATES_JSON = r"""${text}"""
`;
}

/** Terminal width of a cell as Prettier measures it (every character here is narrow). */
function width(text) {
  return [...text].length;
}

/** A Markdown table padded exactly as Prettier 3 aligns it. */
export function markdownTable(headers, rows) {
  const widths = headers.map((header, column) =>
    Math.max(3, width(header), ...rows.map((row) => width(row[column]))),
  );
  const line = (cells) =>
    `| ${cells.map((cell, column) => cell + " ".repeat(widths[column] - width(cell))).join(" | ")} |`;
  return [
    line(headers),
    `| ${widths.map((size) => "-".repeat(size)).join(" | ")} |`,
    ...rows.map(line),
  ].join("\n");
}

function familyTable(remedies, family) {
  return markdownTable(
    ["Remedy", "Failure", "Cause", "Printed fix"],
    remedies
      .filter((entry) => entry.family === family)
      .map((entry) => [
        `\`${entry.id}\``,
        entry.failure,
        entry.cause,
        `\`${entry.fix.replaceAll(PLACEHOLDER, "<$1>")}\``,
      ]),
  );
}

function documentation(current, families, remedies) {
  let text = current;
  for (const family of Object.keys(families)) {
    const begin = `<!-- remedies:${family}:begin -->`;
    const end = `<!-- remedies:${family}:end -->`;
    const start = text.indexOf(begin);
    const stop = text.indexOf(end);
    if (start < 0 || stop < start) {
      throw new Error(
        `${relative(root, DOCS)} has no ${begin} ... ${end} block`,
      );
    }
    text =
      text.slice(0, start + begin.length) +
      `\n\n${familyTable(remedies, family)}\n\n` +
      text.slice(stop);
  }
  return text;
}

function main(argv) {
  const check = argv.includes("--check");
  const { families, remedies } = loadRemedies();
  const outputs = [
    ...TS_OUTPUTS.map((path) => [path, typescriptModule(remedies)]),
    [PY_OUTPUT, pythonModule(remedies)],
    [DOCS, documentation(readFileSync(DOCS, "utf8"), families, remedies)],
  ];
  const stale = [];
  for (const [path, text] of outputs) {
    let current;
    try {
      current = readFileSync(path, "utf8");
    } catch {
      current = undefined;
    }
    if (current === text) continue;
    stale.push(relative(root, path));
    if (!check) writeFileSync(path, text);
  }
  if (check && stale.length > 0) {
    console.error(
      `stale remedies (diagnostics/remedies.json changed): ${stale.join(", ")}; run node scripts/generate-remedies.mjs`,
    );
    return 1;
  }
  if (!check) {
    console.log(
      stale.length === 0
        ? "remedies are up to date"
        : `regenerated ${stale.join(", ")}`,
    );
  }
  return 0;
}

if (
  process.argv[1] !== undefined &&
  fileURLToPath(import.meta.url) === process.argv[1]
) {
  process.exitCode = main(process.argv.slice(2));
}
